#!/usr/bin/env python3
"""verify_reproducibility.py — deterministic byte-level reproducibility probe.

Gates the REPORT.md §8 closing claim ("the results tables above were
regenerated from scratch immediately before this report (artifacts
timestamped in `results/`)") as a *frozen-artifact* statement: the 13
committed `results/` artifacts must be byte-for-byte what the three shipped
writers produce when re-run from scratch today.

This is a reproducibility/machinery probe, not a model reading — it asserts
nothing about physics or metrics, only that the committed artifacts are
reproducible output of the shipped code.  It carries no §7 item citation
(item coverage stays 1..45).

Leg A (re-run, the reproducible statement):
  1. snapshot every file in results/ as committed bytes (start-of-run state);
  2. run the three §8 deterministic writers from scratch, in dependency
     order (ablation.py reads the metrics.csv that run_experiment.py writes):
        python3 run_experiment.py   -> metrics.csv, coefficients_v2.csv,
                                       predictions.csv, comparison.md, plot.svg
        python3 experiment_cmri.py  -> metrics_cmri.csv, ablation_cmri.csv,
                                       coefficients_cmri.csv, predictions_cmri.csv,
                                       comparison_cmri.md, cmri_plot.svg
        python3 ablation.py         -> ablation.csv, ablation.md
  3. compare the regenerated bytes against the committed snapshot per file,
     and confirm the writer produced exactly the committed file set (13/13,
     no missing and no surplus files).

Leg B (honest negative on drift):
  4. if any artifact drifted (bytes changed / missing / surplus) or a writer
     failed, restore the committed bytes from the snapshot so the working
     tree is left clean, print which files differ, and exit 1.

Determinism basis: both runners seed their noise (`random.Random(1234)` at
run_experiment.py:144-146, `random.Random(7)` at cmri_twin.py:219-221) and
embed no timestamps, so re-running the writers yields byte-identical
artifacts (verified on the committed tree).  A future commit that edits or
fabricates a results artifact while the writers would produce different
bytes is exactly what this probe catches.

Pure Python standard library, zero dependencies.  Read-only except for the
results/ artifacts the writers regenerate (and restore on drift).
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).parent
OUT = ROOT / "results"

# (script, [artifacts it writes]) — dependency order: run_experiment.py first,
# then experiment_cmri.py, then ablation.py (reads metrics.csv from step 1).
WRITERS = [
    ("run_experiment.py", [
        "metrics.csv",
        "coefficients_v2.csv",
        "predictions.csv",
        "comparison.md",
        "plot.svg",
    ]),
    ("experiment_cmri.py", [
        "metrics_cmri.csv",
        "ablation_cmri.csv",
        "coefficients_cmri.csv",
        "predictions_cmri.csv",
        "comparison_cmri.md",
        "cmri_plot.svg",
    ]),
    ("ablation.py", [
        "ablation.md",
        "ablation.csv",
    ]),
]


def snapshot(out: pathlib.Path) -> dict[str, bytes]:
    """Read every file in results/ as bytes (the committed state)."""
    return {p.name: p.read_bytes() for p in out.iterdir() if p.is_file()}


def run_writer(script: str) -> tuple[bool, str]:
    proc = subprocess.run(
        [sys.executable, script],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=1800,
    )
    return proc.returncode == 0, proc.stdout


def restore(snap: dict[str, bytes], out: pathlib.Path) -> None:
    """Write the committed bytes back and delete any surplus files."""
    for name, payload in snap.items():
        (out / name).write_bytes(payload)
    for p in out.iterdir():
        if p.is_file() and p.name not in snap:
            p.unlink()


def main() -> int:
    print("verify_reproducibility: committed results/ bytes vs fresh writer output")
    print(f"  results/ = {OUT}")
    print(f"  writers  = {[w[0] for w in WRITERS]} (dependency order)")

    snap = snapshot(OUT)
    committed = set(snap)
    expected = sorted(n for _, names in WRITERS for n in names)
    print(f"  committed artifacts: {len(committed)}  writer-declared: {len(expected)}")
    declared = set(expected)
    if committed != declared:
        missing = sorted(declared - committed)
        surplus = sorted(committed - declared)
        print(f"[FAIL] committed set != writer-declared set", file=sys.stderr)
        if missing:
            print(f"  missing: {missing}", file=sys.stderr)
        if surplus:
            print(f"  surplus: {surplus}", file=sys.stderr)
        return 1

    print("\n-- leg A: re-run the three deterministic writers from scratch --")
    failures: list[str] = []
    for script, _names in WRITERS:
        ok, out = run_writer(script)
        tag = "PASS" if ok else "FAIL"
        print(f"  [{tag}] {script}  (exit {0 if ok else 'nonzero'})")
        if not ok:
            print(out, file=sys.stderr)
            failures.append(f"{script}: writer failed (nonzero exit)")

    regenerated = snapshot(OUT)
    n_match = 0
    for name in sorted(snap):
        if name not in regenerated:
            failures.append(f"{name}: MISSING after re-run")
        elif regenerated[name] != snap[name]:
            failures.append(f"{name}: {len(snap[name])} -> {len(regenerated[name])} bytes (drift)")
        else:
            n_match += 1
            print(f"  [MATCH] {name}")
    for name in sorted(set(regenerated) - set(snap)):
        failures.append(f"{name}: surplus file created by writers")

    print(f"\n-- leg B: honest-negative drift handling --")
    if failures:
        restore(snap, OUT)  # leave the working tree clean
        print(f"[FAIL] {len(failures)} check(s) failed: {len(expected) - n_match} "
              f"artifact file(s) not byte-identical; committed bytes restored — "
              f"tree left clean")
        for f in failures:
            print(f"  diff: {f}", file=sys.stderr)
        print(f"\nVERDICT: FAIL — the §8 'regenerated from scratch' claim is not "
              f"reproducible on this tree; committed artifacts were restored.")
        return 1
    print(f"[PASS] all {n_match} artifacts byte-identical to the committed tree")
    print(f"[PASS] exactly the writer-declared {len(expected)}/13 artifact set, "
          f"no surplus files")
    print(f"\nVERDICT: PASS — the §8 'regenerated from scratch' claim is "
          f"reproducible: the committed results/ artifacts are byte-for-byte "
          f"what run_experiment.py + experiment_cmri.py + ablation.py produce "
          f"from scratch.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
